import { build } from "esbuild";
import { execSync } from "node:child_process";
import { readFileSync, rmSync, writeFileSync } from "node:fs";

const pkg = JSON.parse(readFileSync("package.json", "utf-8"));
writeFileSync(
  "src/sdk-version.ts",
  `// Generated by build.mjs from package.json; do not edit.\nexport const SDK_VERSION = ${JSON.stringify(pkg.version)};\n`,
);

rmSync("dist", { recursive: true, force: true });

// ESM + declarations via tsc
execSync("npx tsc", { stdio: "inherit" });

// CJS bundle via esbuild
await build({
  entryPoints: ["src/index.ts"],
  bundle: true,
  platform: "node",
  target: "node18",
  format: "cjs",
  outfile: "dist/cjs/index.cjs",
  external: ["koffi", "onnxruntime-node"],
  sourcemap: true,
});

writeFileSync("dist/cjs/index.d.cts", `export * from "../esm/index.js";\n`);

console.log("Build complete.");
